/** Rebuild static collision bounds from the actual shipped GLB transforms. */
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import * as THREE from "three";
import { GLTFLoader } from "three/addons/loaders/GLTFLoader.js";
const ids = [
  "pro_barrel",
  "pro_supply_crate",
  "pro_pillar",
  "pro_sarcophagus",
  "pro_memorial",
  "pro_crypt_door",
  "lan_sanctuary_arch_hero",
  "lan_processional_statue",
  "lan_fallen_bell",
  "lan_split_pillar_relief",
  "lan_sealed_sun_door",
  "lan_hiding_tomb",
  "lan_broken_processional_dais",
  "lan_artifact_pedestal",
  "dre_sarcophagus_lid",
  "dre_urn_broken",
];
const bounds: Record<string, unknown> = {};
for (const id of ids) {
  const bytes = await readFile(
    new URL(`../../public/models/catalog/${id}.glb`, import.meta.url),
  );
  const loader = new GLTFLoader().register(() => ({
    name: "BoundsOnly",
    loadTexture: async () => new THREE.Texture(),
  }));
  const gltf = await loader.parseAsync(
    bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength),
    "",
  );
  const box = new THREE.Box3().setFromObject(gltf.scene);
  bounds[id] = {
    min: box.min.toArray(),
    max: box.max.toArray(),
    sha256: createHash("sha256").update(bytes).digest("hex"),
  };
}
await writeFile(
  new URL("../../src/prop-bounds.ts", import.meta.url),
  "// Generated by tools/assets/collision-bounds.ts from shipped GLBs.\n" +
    "export const propBounds: Record<string,{min:number[];max:number[];sha256:string}> = " +
    JSON.stringify(bounds, null, 2) +
    ";\n",
);
console.log("Generated collision bounds for", ids.length, "GLBs");
