"""Generate serial, versioned torch-carry motion sources with the official HF Space.

Run with the user's authenticated local Python/Hugging Face installation.
Never resubmit an uncertain generation automatically.
"""
import argparse,hashlib,json,shutil,time
from pathlib import Path
from gradio_client import Client
from huggingface_hub import get_token

ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'art-source/torchbearer-rebuild/motions'
PROMPTS={
'idle':'A person stands still, breathing gently and looking forward. The right elbow is bent, holding a torch upright in the right hand just outside the right shoulder. The left arm rests naturally beside the body. Keep both feet planted. No stepping, turning, pointing, reaching or waving.',
'walk':'A person walks forward steadily, carrying a lit torch upright in the right hand. Right elbow bent around ninety degrees and right forearm upright, hand just outside the shoulder. Left arm swings naturally. Smooth repeated walking steps, upright torso, no turning or stopping.',
'sprint':'A person runs forward urgently while carefully carrying a torch upright in the right hand. The right elbow stays bent, right wrist held outside the shoulder, right forearm pointing up. The left arm pumps naturally. Smooth repeated running strides, no turning, no stopping, no jumping.',
'crouch_idle':'A person stays in a low crouch with both feet planted and knees bent, carefully holding a torch upright in the right hand in front of the right shoulder. The left hand stays near the left knee for balance. Small breathing movement, no stepping and no standing up.',
'crouch_walk':'A person moves forward slowly in a low crouch with bent knees, holding a torch upright in the right hand near the right shoulder. Left hand stays forward for balance. Repeated quiet low crouching steps, no standing up, no crawling on hands, no turning.',
'interact':'A person stands holding a torch upright in the right hand near the right shoulder. The person reaches forward once with the left hand, picks up a small item at waist height, and brings the left arm back to the side. The right hand continues holding the torch upright. Feet stay planted.',
'relight':'A person holds an unlit torch upright in the right hand at chest height. The left hand strikes a match and brings it carefully toward the top of the torch, pauses briefly, then returns to the side while the right hand raises the relit torch near shoulder height. Feet stay planted.',
'burst':'A person carrying a torch in the bent right arm thrusts the torch forward once defensively, recoils slightly from the flash, and brings the right arm back to a steady upright torch carrying position near the right shoulder. Feet stay planted, left hand shields the face briefly.',
'death':'A person holding a torch in the right hand stumbles, falls to both knees, then collapses onto the ground and stays down. The person does not get back up. One continuous natural fall.'
}
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--clips',nargs='+',choices=PROMPTS,default=list(PROMPTS))
parser.add_argument('--regenerate-missing',action='store_true',help='Explicitly regenerate completed sources absent from this clone; preserves prior records locally')
args=parser.parse_args();OUT.mkdir(parents=True,exist_ok=True);(OUT/'raw').mkdir(exist_ok=True)
client=Client('tencent/HY-Motion-1.0',token=get_token(),verbose=False,download_files=str(OUT/'raw/downloads'))
for name in args.clips:
 previous=None
 record=OUT/(name+'.json')
 if record.exists():
  old=json.loads(record.read_text())
  if old['status']=='complete':
   f=ROOT/old['file']
   if f.exists():
    assert hashlib.sha256(f.read_bytes()).hexdigest()==old['sha256'];print(name,'already complete',flush=True);continue
   if not args.regenerate_missing:raise RuntimeError(f'{name}: restore the local raw FBX or explicitly use --regenerate-missing; generated bytes may differ')
   history=ROOT/'.asset-tools/rebuilt-motion-history';history.mkdir(parents=True,exist_ok=True)
   shutil.copy2(record,history/(name+'-'+old['sha256']+'.json'));previous=old
  else:raise RuntimeError(f'{name} has an unresolved submission; inspect the provider before retrying')
 i=list(PROMPTS).index(name);prompt=PROMPTS[name]
 request={'original_text':prompt,'rewritten_text':prompt,'seed_input':str(211019+i),'motion_duration':4.0,'cfg_scale':5.0}
 if previous:
  request=previous.get('request') or {key:previous[key] for key in request}
 data={'space':'tencent/HY-Motion-1.0','model':'tencent/HY-Motion-1.0','api':'/generate_motion_func','status':'submitting','submitted_at':time.time(),'request':request}
 if previous:data['regenerated_from_sha256']=previous['sha256']
 record.write_text(json.dumps(data,indent=2));print('Generating',name,flush=True)
 try:
  result=client.predict(**request,api_name='/generate_motion_func')
  fbx=next(Path(f) for f in result[1] if Path(f).read_bytes().startswith(b'Kaydara FBX Binary'))
  dest=OUT/'raw'/(name+'.fbx');shutil.copy2(fbx,dest)
  data.update(status='complete',file=dest.relative_to(ROOT).as_posix(),sha256=hashlib.sha256(dest.read_bytes()).hexdigest(),bytes=dest.stat().st_size,completed_at=time.time())
  record.write_text(json.dumps(data,indent=2));print(name,'complete',dest.stat().st_size,'bytes',flush=True)
 except Exception as exc:
  data.update(status='uncertain',error=str(exc));record.write_text(json.dumps(data,indent=2));raise
